//! The index table as a frozen record: how the live keyboard is written out,
//! how a frozen file is read back, and how the two are told apart.
//!
//! The record is generated *from* [`table`], never hand-written, so the file
//! is a photograph of the declarations rather than a second copy of them that
//! could drift. One line per Operator in index order, tab-separated, pinning
//! exactly the nine things Requirement 6 criterion 3 holds still — index,
//! name, family, arity, operand types, result type, idempotence, inverse case
//! and tolerance. The spectral gate is deliberately absent: task 3.13 owns it
//! and leaves it unmeasured, so pinning it here would freeze a `None`.
//!
//! The frozen file is `phical/tests/keyboard/index.golden`, and
//! `phical/tests/keyboard.rs` is the test that compares it against
//! [`render`]. When they differ, [`drift::between`] names what moved — an
//! Operator added, removed, renamed or re-typed — and the re-recording path
//! in [`record`] is the only way to move the file, carrying the previous
//! table, the new table and the stated reason (Requirement 11 criterion 10).
//!
//! The tolerance is written to twelve decimal places rather than to full
//! precision on purpose. The one approximate inverse's tolerance is computed
//! (`1 − cos(π/64)`), and a platform's `cos` may differ in its last bit; a
//! frozen record must not fail for that, and twelve places is far finer than
//! the 0.0099 cap the tolerance is judged against.

use super::operator::{table, Inverse, Operator};

pub mod drift;
pub mod record;

pub use drift::Drift;
pub use record::{Part, Rerecord, Verdict};

/// What a field with no value is written as: an absent tolerance, say.
pub const NONE: &str = "-";

/// The column separator. A tab, so a name or a type is never split by one.
const TAB: &str = "\t";

/// The decimal places a tolerance is written to.
const PLACES: usize = 12;

/// The comment block every frozen record opens with. It names the file's
/// own re-recording rule, because that rule is the thing most easily
/// forgotten by whoever next sees the file fail.
pub const HEAD: &str = "\
# phical keyboard — the frozen index table of the 64 Operators (R6.2, R6.3).
#
# Generated by `cargo run -p phical --example freeze`. Do not edit by hand.
#
# Re-record only through `phical::keyboard::index::record`: the previous
# table, the new table and the stated reason, all three. Any one of the three
# absent is recorded `unjudged` and fails (R11.10).
#
# index\tname\tfamily\tarity\toperands\tresult\tidempotent\tinverse\ttolerance
";

/// The live keyboard written out in the frozen format: the [`HEAD`] comment
/// block, then one [`line`] per Operator in index order, each ending in a
/// newline. This is the whole of what the golden file holds.
pub fn render() -> String {
    let mut text = String::from(HEAD);
    for op in table() {
        text.push_str(&line(&op));
        text.push('\n');
    }
    text
}

/// One Operator as one record line.
pub fn line(op: &Operator) -> String {
    let operands: Vec<&str> = op.operands.iter().map(|ty| ty.name()).collect();
    let (inverse, tolerance) = case(op.inverse);
    let fields = [
        op.index.to_string(),
        op.name.to_string(),
        op.family.name().to_string(),
        op.arity.to_string(),
        operands.join(","),
        op.result.name().to_string(),
        flag(op.idempotent).to_string(),
        inverse,
        tolerance,
    ];
    fields.join(TAB)
}

/// An inverse case as its two written fields: the case's name, and the
/// declared tolerance an approximate case carries.
fn case(inverse: Inverse) -> (String, String) {
    match inverse {
        Inverse::Exact => ("exact".to_string(), NONE.to_string()),
        Inverse::None => ("none".to_string(), NONE.to_string()),
        Inverse::Approximate { tolerance } => {
            ("approximate".to_string(), format!("{:.*}", PLACES, tolerance))
        }
    }
}

/// A declared flag as the record spells it.
const fn flag(yes: bool) -> &'static str {
    if yes {
        "yes"
    } else {
        "no"
    }
}

/// One row read back from a frozen record. Every field is held as the text
/// the record carries, including the tolerance, so comparing a frozen row
/// against a live one is a comparison of what was written rather than of a
/// float re-parsed two different ways.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    pub index: u8,
    pub name: String,
    pub family: String,
    pub arity: u8,
    pub operands: Vec<String>,
    pub result: String,
    pub idempotent: bool,
    pub inverse: String,
    /// The declared tolerance as written, or `None` where the record wrote
    /// [`NONE`].
    pub tolerance: Option<String>,
}

/// Why a record could not be read: the line it happened on, counted from 1
/// over the file as a whole, and what was wrong with it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Flaw {
    pub line: usize,
    pub reason: String,
}

impl std::fmt::Display for Flaw {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "line {}: {}", self.line, self.reason)
    }
}

/// A frozen record read back into rows. Comment lines (`#`) and blank lines
/// are skipped; a carriage return at a line's end is dropped, so a record
/// checked out with either line ending reads the same.
///
/// The rows must be in index order with each row's own `index` field equal
/// to its position, which is the same bijection [`table`] asserts over the
/// live keyboard — a record that is not in that shape is a flaw, not a
/// drift, because nothing can be compared against it position by position.
pub fn parse(text: &str) -> Result<Vec<Row>, Flaw> {
    let mut rows: Vec<Row> = Vec::new();
    for (at, raw) in text.lines().enumerate() {
        let at = at + 1;
        let body = raw.strip_suffix('\r').unwrap_or(raw);
        if body.trim().is_empty() || body.starts_with('#') {
            continue;
        }
        let row = row(at, body)?;
        if row.index as usize != rows.len() {
            return Err(Flaw {
                line: at,
                reason: format!(
                    "row {} declares index {} but sits at position {}",
                    row.name,
                    row.index,
                    rows.len()
                ),
            });
        }
        rows.push(row);
    }
    Ok(rows)
}

/// One record line read back.
fn row(at: usize, body: &str) -> Result<Row, Flaw> {
    let fields: Vec<&str> = body.split(TAB).collect();
    if fields.len() != 9 {
        return Err(Flaw {
            line: at,
            reason: format!("{} tab-separated fields, expected 9", fields.len()),
        });
    }
    let index = number(at, "index", fields[0])?;
    let arity = number(at, "arity", fields[3])?;
    let operands: Vec<String> = fields[4].split(',').map(str::to_string).collect();
    if operands.len() != arity as usize {
        return Err(Flaw {
            line: at,
            reason: format!("arity {arity} against {} operand types", operands.len()),
        });
    }
    Ok(Row {
        index,
        name: fields[1].to_string(),
        family: fields[2].to_string(),
        arity,
        operands,
        result: fields[5].to_string(),
        idempotent: judged(at, fields[6])?,
        inverse: fields[7].to_string(),
        tolerance: (fields[8] != NONE).then(|| fields[8].to_string()),
    })
}

fn number(at: usize, field: &str, text: &str) -> Result<u8, Flaw> {
    text.parse().map_err(|_| Flaw { line: at, reason: format!("{field} {text:?} is not a u8") })
}

fn judged(at: usize, text: &str) -> Result<bool, Flaw> {
    match text {
        "yes" => Ok(true),
        "no" => Ok(false),
        other => Err(Flaw { line: at, reason: format!("idempotent {other:?} is not yes or no") }),
    }
}

